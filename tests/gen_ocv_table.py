#!/usr/bin/env python3
"""Generate the YDL375678 OCV table from the nPM1300 profiler output.

Reads the fitted OCV curve (Tparam_3) from the battery profiler's
profileSettings.json and emits the C table used in
zmk/app/src/battery_profile_ydl375678.h, plus (with --expected) a header
of (soc, mv) reference pairs for the unit test.
"""

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
PROFILE_JSON = REPO_ROOT / "zmk-keyboard-pipar/nrf-bat-profile/YDL375678/profileSettings.json"

# The profiler's fit extrapolates non-physically below 1% SOC; 0% is
# defined by its 3.0V lower cutoff instead.
EMPTY_MV = 2990


def load_curve():
    settings = json.loads(PROFILE_JSON.read_text())
    params = json.loads(settings["profiles"][0]["paramsJson"])
    soc, ocv = params["Tparam_3"]
    return soc, ocv


def v_at(soc, ocv, s):
    for i in range(len(soc) - 1):
        if soc[i] <= s <= soc[i + 1]:
            f = (s - soc[i]) / (soc[i + 1] - soc[i])
            return (ocv[i] + (ocv[i + 1] - ocv[i]) * f) * 1000
    return ocv[-1] * 1000


def build_table():
    soc, ocv = load_curve()
    mv = [round(v_at(soc, ocv, i / 100)) for i in range(101)]
    mv[0] = EMPTY_MV
    if not all(a < b for a, b in zip(mv, mv[1:])):
        sys.exit("generated table is not strictly monotonic")
    return mv


def format_c_table(mv):
    lines = []
    for i in range(0, len(mv), 16):
        lines.append("    " + ", ".join(str(v) for v in mv[i:i + 16]) + ",")
    return "\n".join(lines).rstrip(",") + "};"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--expected", metavar="OUT",
                        help="write expected_ocv.h with reference pairs for the unit test")
    args = parser.parse_args()

    mv = build_table()

    if args.expected:
        pairs = ", ".join(f"{{{i}, {v}}}" for i, v in enumerate(mv))
        Path(args.expected).write_text(
            "// Generated by gen_ocv_table.py — do not edit.\n"
            "static const struct { int pct; int mv; } expected_ocv[] = {" + pairs + "};\n")
        print(f"wrote {args.expected} ({len(mv)} reference points)")
    else:
        print("static const uint16_t battery_ocv_table[] = {")
        print(format_c_table(mv))


if __name__ == "__main__":
    main()
